/**
 * @file ks_linux_internal.h
 * @brief Внутренние типы и структуры Linux-реализации KernelSocket.
 *
 * @details
 * Файл предназначен для внутреннего использования в `src/linux/` и не является 
 * частью публичного API. Он содержит платформозависимое представление 
 * непрозрачного дескриптора `KS_SOCKET`, скрывающее особенности работы 
 * с сетевым стеком ядра Linux.
 */

#ifndef KS_LINUX_INTERNAL_H
#define KS_LINUX_INTERNAL_H

#include <linux/net.h>
#include <linux/in.h>
#include "../../include/ks_api.h"

/* =========================================================================
 * Внутренняя структура сокета для Linux
 * ========================================================================= */

/**
 * @struct KS_SOCKET
 * @brief Внутреннее представление сетевого сокета для ОС Linux.
 * 
 * @details Данная структура скрыта от пользователя API посредством паттерна Opaque Pointer.
 * В отличие от Windows-реализации, в Linux сокет ядра создается сразу, без
 * использования отложенной (ленивой) инициализации.
 */
struct KS_SOCKET {
    int Protocol;          /**< Транспортный протокол (KS_TCP или KS_UDP). */
    struct socket *sock;   /**< Указатель на стандартный объект сокета ядра Linux (создается через sock_create_kern). */
};

#endif /* KS_LINUX_INTERNAL_H */